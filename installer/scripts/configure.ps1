#Requires -Version 5.1
param(
    [string]$InstallRoot = (Split-Path $PSScriptRoot -Parent)
)

$ErrorActionPreference = "Stop"

$apiDir = Join-Path $InstallRoot "api"
$dashboardDir = Join-Path $InstallRoot "dashboard"
$configPath = Join-Path $env:ProgramData "Helm\install-config.json"

function New-Secret {
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return [Convert]::ToBase64String($bytes) -replace "[+/=]", "x"
}

function Read-SecretPlain {
    param([string]$Prompt)
    $secure = Read-Host $Prompt -AsSecureString
    $ptr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
    try { return [Runtime.InteropServices.Marshal]::PtrToStringBSTR($ptr) }
    finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($ptr) }
}

Write-Host ""
Write-Host "Helm setup" -ForegroundColor Cyan
Write-Host "Database name: bidautomation (PostgreSQL on this PC)" -ForegroundColor DarkGray
Write-Host ""

$pgPassword = Read-SecretPlain "PostgreSQL password (user: postgres)"
if (-not $pgPassword) { throw "PostgreSQL password is required." }

& (Join-Path $PSScriptRoot "init-database.ps1") -PostgresPassword $pgPassword

$adminEmail = Read-Host "Admin email (Helm login)"
if (-not $adminEmail -or $adminEmail -notmatch "@") { throw "Valid admin email is required." }

$adminPassword = Read-SecretPlain "Admin password (min 6 characters)"
if ($adminPassword.Length -lt 6) { throw "Admin password must be at least 6 characters." }

$openaiKey = Read-Host "OpenAI API key (optional - Enter to skip mock proposals)"
$authSecret = New-Secret

$databaseUrl = "postgresql://postgres:$([uri]::EscapeDataString($pgPassword))@localhost:5432/bidautomation"

$apiEnv = @"
# Generated by Helm setup - $(Get-Date -Format o)
OPENAI_API_KEY=$openaiKey
SUPABASE_URL=
SUPABASE_SERVICE_KEY=
SUPABASE_JWT_SECRET=
GEMINI_API_KEY=
CORS_ORIGINS=http://localhost:3001,http://127.0.0.1:3001,chrome-extension://
DEV_MODE=false
LOCAL_AUTH_SECRET=$authSecret
ALLOW_DEV_TOKEN=false
ADMIN_EMAIL=$adminEmail
ADMIN_PASSWORD=$adminPassword
DATABASE_URL=$databaseUrl
MIGRATE_JSON_ON_STARTUP=false
LOCAL_PERSISTENCE=false
LOCAL_DATA_PATH=data/store.json
"@

$dashboardEnv = @"
# Generated by Helm setup
NEXT_PUBLIC_API_URL=http://127.0.0.1:8000
"@

Set-Content -Path (Join-Path $apiDir ".env") -Value $apiEnv.TrimEnd() -Encoding UTF8
Set-Content -Path (Join-Path $dashboardDir ".env.local") -Value $dashboardEnv.TrimEnd() -Encoding UTF8

$configDir = Split-Path $configPath -Parent
if (-not (Test-Path $configDir)) { New-Item -ItemType Directory -Path $configDir -Force | Out-Null }

@{
    install_root = $InstallRoot
    database = "bidautomation"
    configured_at = (Get-Date).ToString("o")
} | ConvertTo-Json | Set-Content -Path $configPath -Encoding UTF8

Write-Host ""
Write-Host "Configuration saved." -ForegroundColor Green
Write-Host "  API env:      $apiDir\.env"
Write-Host "  Dashboard:    $dashboardDir\.env.local"
Write-Host ""
Write-Host "Use 'Start Helm' from the Start Menu, or run scripts\start-helm.ps1" -ForegroundColor Cyan
Write-Host ""
