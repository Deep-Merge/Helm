async function loadProfileDirection() {
    try {
        const { profile } = await getProfile();
        const parts = [profile.proposal_style, profile.default_direction].filter(Boolean);
        profileDirection = parts.join("\n\n");
    }
    catch {
        const settings = await getSettings();
        profileDirection = settings.defaultDirection;
    }
}
function ensurePanelDirectionFromSettings() {
    if (profileDirection)
        return;
    void getSettings().then((settings) => {
        if (!profileDirection)
            profileDirection = settings.defaultDirection;
    });
}
