function onFill() {
    const proposal = panelRoot?.querySelector("#ba-proposal")?.value?.trim();
    const questions = panelRoot?.querySelector("#ba-questions")?.value?.trim();
    const budgetRaw = panelRoot?.querySelector("#ba-budget")?.value;
    const timelineRaw = panelRoot?.querySelector("#ba-timeline")?.value;
    if (!proposal) {
        toast("Generate or enter a proposal first", "error");
        return;
    }
    const budget = budgetRaw ? Number(budgetRaw) : NaN;
    const timeline = timelineRaw ? Number(timelineRaw) : NaN;
    const filled = [];
    const failed = [];
    if (fillProposal(proposal))
        filled.push("proposal");
    else
        failed.push("proposal");
    if (Number.isFinite(budget) && budget > 0) {
        if (fillBidAmount(budget))
            filled.push("bid amount");
        else
            failed.push("bid amount");
    }
    if (Number.isFinite(timeline) && timeline > 0) {
        if (fillDeliveryDays(timeline))
            filled.push("timeline");
        else
            failed.push("timeline");
    }
    if (questions) {
        const questionText = parseQuestionsText(questions).join("\n");
        if (fillQuestions(questionText))
            filled.push("questions");
        else
            failed.push("questions");
    }
    if (!failed.length) {
        toast(`Filled: ${filled.join(", ")}`);
    }
    else {
        toast(`Filled ${filled.join(", ")} — not found: ${failed.join(", ")}`, "error");
    }
    scrollToBidActions();
}
function makeDraggable(panel) {
    const header = panel.querySelector(".ba-panel__header");
    let ox = 0, oy = 0, mx = 0, my = 0;
    header.addEventListener("mousedown", (e) => {
        mx = e.clientX;
        my = e.clientY;
        const rect = panel.getBoundingClientRect();
        ox = rect.left;
        oy = rect.top;
        const onMove = (ev) => {
            panel.style.left = `${ox + ev.clientX - mx}px`;
            panel.style.top = `${oy + ev.clientY - my}px`;
            panel.style.right = "auto";
        };
        const onUp = () => {
            document.removeEventListener("mousemove", onMove);
            document.removeEventListener("mouseup", onUp);
        };
        document.addEventListener("mousemove", onMove);
        document.addEventListener("mouseup", onUp);
    });
}
