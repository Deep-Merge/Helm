function watchFreelancerProjectNavigation() {
    let lastKey = projectPageKey();
    let lastIdentity = extractProjectId();
    const onNavigate = () => {
        const key = projectPageKey();
        const identity = extractProjectId();
        if (key === lastKey)
            return;
        const sameProject = !!lastIdentity && !!identity && lastIdentity === identity;
        lastKey = key;
        lastIdentity = identity;
        if (isProjectProposalsPage()) {
            lastAutoGeneratedKey = key;
            collapsePanelIfOpen();
            return;
        }
        if (sameProject &&
            (isBidAlreadyPlacedOnPage() || isLocallySubmitted())) {
            lastAutoGeneratedKey = key;
            void openPanelOnProjectPage();
            return;
        }
        if (!isProjectBidPage()) {
            lastAutoGeneratedKey = key;
            collapsePanelIfOpen();
            return;
        }
        lastAutoGeneratedKey = null;
        lastScrapedSnapshot = null;
        void onProjectPageReady();
    };
    window.addEventListener("popstate", onNavigate);
    window.addEventListener("hashchange", onNavigate);
    const wrapHistory = (method) => function (...args) {
        const result = method.apply(this, args);
        onNavigate();
        return result;
    };
    history.pushState = wrapHistory(history.pushState);
    history.replaceState = wrapHistory(history.replaceState);
    window.setInterval(() => {
        const key = projectPageKey();
        if (key !== lastKey)
            onNavigate();
    }, 1000);
}
function shouldIgnoreHotkeyTarget(target) {
    if (!(target instanceof HTMLElement))
        return false;
    if (target.closest(".ba-panel, .ba-fab"))
        return false;
    const tag = target.tagName;
    if (tag === "INPUT" || tag === "TEXTAREA" || tag === "SELECT")
        return true;
    return target.isContentEditable;
}
async function handleHotkeyAction(action) {
    if (!isProjectDetailPage())
        return;
    await initPanel();
    panelRoot?.classList.remove("ba-panel--collapsed");
    if (action === "copyProposal")
        onCopyProposal();
    else if (action === "copyQuestions")
        onCopyQuestions();
    else
        onFill();
}
async function refreshHotkeyBindings() {
    hotkeyBindings = await readHotkeyBindings();
}
function attachHotkeyListener() {
    if (hotkeysAttached)
        return;
    hotkeysAttached = true;
    void (async () => {
        await refreshHotkeyBindings();
        chrome.storage.onChanged.addListener((changes, area) => {
            if (area !== "local")
                return;
            if (changes.hotkeyCopyProposal ||
                changes.hotkeyCopyQuestions ||
                changes.hotkeyFillForm) {
                void refreshHotkeyBindings();
            }
        });
        window.addEventListener("keydown", (event) => {
            if (!isProjectDetailPage() || !hotkeyBindings)
                return;
            if (shouldIgnoreHotkeyTarget(event.target) || event.repeat)
                return;
            const action = findActionForEvent(event, hotkeyBindings);
            if (!action)
                return;
            event.preventDefault();
            event.stopPropagation();
            void handleHotkeyAction(action);
        }, true);
    })();
}
