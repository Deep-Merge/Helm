async function tryDashboardSubmittedFill() {
    if (!isProjectBidPage())
        return false;
    if (autoGenerateInFlight)
        return false;
    autoGenerateInFlight = true;
    try {
        const urlFillId = readUrlFillHandoffProjectId();
        const handoff = await resolvePendingFillHandoffFast();
        if (!handoff?.fillSubmitted || !handoff.bid) {
            if (urlFillId) {
                toast("Could not load your submitted bid from the dashboard. Connect the extension and reload it.", "error");
            }
            return false;
        }
        const handoffId = handoff.project.dashboard_project_id;
        if (lastDashboardFillId === handoffId)
            return true;
        await clearDashboardHandoff();
        lastScrapedSnapshot = handoffToScrapedProject(handoff);
        lastProjectId = handoffId;
        await initPanelFast();
        setLoading(false);
        applySubmittedBidToPanel(handoff.bid, handoffId, handoff.bid.bid_id);
        markProjectSubmittedLocally(handoff.project.freelancer_project_id);
        lastDashboardFillId = handoffId;
        toast("Loaded your submitted bid");
        return true;
    }
    finally {
        autoGenerateInFlight = false;
    }
}
async function tryDashboardHandoffGenerate() {
    if (!isProjectBidPage())
        return;
    if (autoGenerateInFlight)
        return;
    autoGenerateInFlight = true;
    try {
        const urlHandoffId = readUrlHandoffProjectId();
        const handoff = await resolvePendingHandoffFast();
        if (!handoff?.autoGenerate) {
            if (urlHandoffId) {
                toast("Could not load project from dashboard. Connect the extension (Connect extension page) and reload it.", "error");
            }
            return;
        }
        if (isDashboardHandoffSubmitted(handoff))
            return;
        const handoffId = handoff.project.dashboard_project_id;
        if (lastDashboardHandoffId === handoffId)
            return;
        await clearDashboardHandoff();
        const scraped = handoffToScrapedProject(handoff);
        lastScrapedSnapshot = scraped;
        lastProjectId = handoffId;
        await initPanelFast();
        setLoading(true);
        panelRoot?.querySelector("#ba-output")?.classList.add("ba-output--hidden");
        panelRoot?.querySelector("#ba-loading")?.classList.remove("ba-loading--hidden");
        let lastError = null;
        for (let attempt = 0; attempt < 2; attempt += 1) {
            try {
                if (attempt > 0) {
                    await new Promise((resolve) => window.setTimeout(resolve, 800));
                }
                await runGenerate({
                    silent: true,
                    project: scraped,
                    dashboardProjectId: handoffId,
                    fromDashboard: true,
                });
                lastDashboardHandoffId = handoffId;
                lastAutoGeneratedKey = projectPageKey();
                lastError = null;
                break;
            }
            catch (e) {
                lastError = e;
            }
        }
        if (lastError) {
            const message = friendlyApiError(lastError);
            setPanelStatus(message, "error");
            toast(message, "error");
        }
    }
    finally {
        autoGenerateInFlight = false;
    }
}
function attachHandoffStorageListener() {
    if (handoffListenerAttached)
        return;
    handoffListenerAttached = true;
    chrome.storage.onChanged.addListener((changes, area) => {
        if (area !== "local")
            return;
        const next = changes[DASHBOARD_HANDOFF_STORAGE_KEY]?.newValue;
        if (!next)
            return;
        if (next.project?.dashboard_project_id !== lastDashboardHandoffId) {
            lastDashboardHandoffId = null;
        }
        if (next.project?.dashboard_project_id !== lastDashboardFillId) {
            lastDashboardFillId = null;
        }
        if (!isProjectBidPage())
            return;
        void onProjectPageReady();
    });
}
async function onProjectPageReady() {
    if (!isProjectBidPage())
        return;
    const filled = await tryDashboardSubmittedFill();
    if (filled)
        return;
    await tryDashboardHandoffGenerate();
    if (!panelRoot) {
        await openPanelOnProjectPage();
    }
}
