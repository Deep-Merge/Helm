function normalizeQuestionLine(line) {
    return line.trim().replace(/^[-–•]\s*/, "");
}
function formatQuestionsDisplay(questions) {
    return questions
        .map((q) => normalizeQuestionLine(String(q)))
        .filter(Boolean)
        .map((q) => ` - ${q}`)
        .join("\n");
}
function parseQuestionsText(text) {
    return text
        .split("\n")
        .map((line) => normalizeQuestionLine(line))
        .filter(Boolean);
}
function resolveFeasibility(feasibility, riskScore) {
    const raw = (feasibility || "").trim().toLowerCase().replace(/-/g, "_");
    if (raw === "full" || raw === "fully_feasible" || raw === "feasible")
        return "full";
    if (raw === "partial" || raw === "partially_feasible")
        return "partial";
    if (raw === "not_feasible" || raw === "not" || raw === "infeasible")
        return "not_feasible";
    if (typeof riskScore === "number") {
        if (riskScore <= 25)
            return "full";
        if (riskScore <= 55)
            return "partial";
        return "not_feasible";
    }
    return "partial";
}
const FEASIBILITY_LABELS = {
    full: "Fully feasible",
    partial: "Partially feasible",
    not_feasible: "Not feasible",
};
function renderFeasibility(feasibility, notes, riskScore) {
    const block = panelRoot?.querySelector("#ba-feasibility");
    const badge = panelRoot?.querySelector("#ba-feasibility-badge");
    const note = panelRoot?.querySelector("#ba-feasibility-note");
    if (!block || !badge || !note)
        return;
    const level = resolveFeasibility(feasibility, riskScore);
    const summary = notes?.trim();
    badge.textContent = FEASIBILITY_LABELS[level];
    badge.className = `ba-feasibility__badge ba-feasibility__badge--${level}`;
    const riskLine = typeof riskScore === "number" ? `Risk score: ${riskScore}/100.` : "";
    note.textContent = [summary, riskLine].filter(Boolean).join(" ") || "No feasibility notes.";
    block.classList.remove("ba-feasibility--hidden");
}
