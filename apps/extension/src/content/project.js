/** Freelancer project page where you compose/place a bid — not /proposals or other sub-routes. */
function isProjectBidPage() {
    if (!/^\/projects\//i.test(window.location.pathname))
        return false;
    if (isProjectProposalsPage())
        return false;
    // Other project sub-pages that are not the bid form.
    if (/\/(?:proposals|messages|repost|share)(?:\/|$)/i.test(window.location.pathname))
        return false;
    return true;
}
