async function runGenerate(options = {}) {
    if (!panelRoot)
        return;
    if (!options.fromDashboard) {
        const connection = await verifyApiConnection();
        if (!connection.ok) {
            setPanelStatus(connection.message, "error");
            toast(connection.message, "error");
            throw new Error(connection.message);
        }
        await loadProfileDirection();
    }
    else {
        ensurePanelDirectionFromSettings();
    }
    setPanelStatus(null);
    setLoading(true);
    try {
        const scraped = options.project ?? (await scrapeProjectAsync(lastScrapedSnapshot ?? undefined));
        lastScrapedSnapshot = scraped;
        const settings = await getSettings();
        const result = await generateBid({
            ...scraped,
            project_id: options.dashboardProjectId ?? lastProjectId,
            direction: profileDirection || undefined,
            model_tier: settings.modelTier,
        });
        applyGenerateResult(result);
        if (!options.fromDashboard) {
            await refreshSubmittedBidEstimates(scraped);
        }
        else {
            setBidEstimatesVisible(true);
        }
        scrollPageToTop();
        if (!options.silent)
            toast("Generated");
    }
    catch (e) {
        const message = friendlyApiError(e);
        setPanelStatus(message, "error");
        toast(message, "error");
        throw e;
    }
    finally {
        setLoading(false);
    }
}
