const SUBMITTED_STATUSES = new Set(["submitted", "won", "lost"]);
const SUBMITTED_PROJECTS_STORAGE_KEY = "ba-submitted-projects";
function loadSubmittedProjectIds() {
    try {
        const raw = sessionStorage.getItem(SUBMITTED_PROJECTS_STORAGE_KEY);
        if (!raw)
            return new Set();
        const ids = JSON.parse(raw);
        return new Set(Array.isArray(ids) ? ids : []);
    }
    catch {
        return new Set();
    }
}
let submittedFreelancerIds = loadSubmittedProjectIds();
function persistSubmittedProjectIds() {
    sessionStorage.setItem(SUBMITTED_PROJECTS_STORAGE_KEY, JSON.stringify([...submittedFreelancerIds]));
}
function markProjectSubmittedLocally(freelancerId) {
    for (const key of projectIdentityKeys(lastScrapedSnapshot)) {
        submittedFreelancerIds.add(key);
    }
    if (freelancerId)
        submittedFreelancerIds.add(freelancerId);
    persistSubmittedProjectIds();
}
function unmarkProjectSubmittedLocally(scraped) {
    for (const key of projectIdentityKeys(scraped)) {
        submittedFreelancerIds.delete(key);
    }
    persistSubmittedProjectIds();
}
function projectIdentityKeys(scraped) {
    const keys = new Set();
    const resolved = resolveFreelancerProjectId(scraped);
    if (resolved)
        keys.add(resolved);
    if (scraped?.freelancer_project_id)
        keys.add(scraped.freelancer_project_id);
    const path = window.location.pathname.replace(/\/proposals\/?$/i, "").replace(/\/$/, "");
    const match = path.match(/\/projects\/(.+)$/i);
    if (match)
        keys.add(match[1].toLowerCase());
    return [...keys];
}
function isLocallySubmitted(scraped) {
    return projectIdentityKeys(scraped).some((key) => submittedFreelancerIds.has(key));
}
function resolveFreelancerProjectId(scraped) {
    return (scraped?.freelancer_project_id ??
        lastScrapedSnapshot?.freelancer_project_id ??
        extractProjectId());
}
async function isProjectAlreadySubmitted(scraped) {
    // Freelancer's bid form wins over stale session/dashboard state.
    if (canPlaceBidOnPage()) {
        unmarkProjectSubmittedLocally(scraped);
        return false;
    }
    if (isBidAlreadyPlacedOnPage())
        return true;
    if (isLocallySubmitted(scraped))
        return true;
    const keys = projectIdentityKeys(scraped);
    if (!keys.length)
        return false;
    try {
        const statuses = await getProjectStatusMap();
        return keys.some((key) => SUBMITTED_STATUSES.has(statuses[key] ?? ""));
    }
    catch {
        return false;
    }
}
