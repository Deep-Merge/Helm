function getPanelBidData() {
    const proposal = panelRoot?.querySelector("#ba-proposal")?.value?.trim() || "";
    const questionsRaw = panelRoot?.querySelector("#ba-questions")?.value?.trim() || "";
    const budgetRaw = panelRoot?.querySelector("#ba-budget")?.value;
    const timelineRaw = panelRoot?.querySelector("#ba-timeline")?.value;
    const budget = budgetRaw ? Number(budgetRaw) : null;
    const timeline = timelineRaw ? Number(timelineRaw) : null;
    return {
        proposal_text: proposal,
        bid_amount: budget != null && Number.isFinite(budget) ? budget : null,
        delivery_days: timeline != null && Number.isFinite(timeline) ? timeline : null,
        questions: questionsRaw ? parseQuestionsText(questionsRaw) : [],
    };
}
function isBidForm(form) {
    if (form.closest(".ba-panel, .ba-fab"))
        return false;
    return !!(form.querySelector("textarea") &&
        form.querySelector('input[type="number"], input[type="text"]'));
}
async function onPlaceBidClicked() {
    if (placeBidSaving)
        return;
    placeBidSaving = true;
    // Read Freelancer form immediately — page may navigate after Place Bid is clicked.
    const form = readBidFormValues();
    try {
        const scraped = await scrapeProjectAsync(lastScrapedSnapshot ?? undefined);
        lastScrapedSnapshot = scraped;
        const formQuestions = form.questions
            .split("\n")
            .map((q) => q.trim())
            .filter(Boolean);
        if (!form.proposal.trim()) {
            toast("No proposal found in Freelancer form", "error");
            return;
        }
        const result = await submitBid({
            ...scraped,
            project_id: lastProjectId,
            bid_id: lastBidId,
            proposal_text: form.proposal,
            bid_amount: form.bid_amount,
            delivery_days: form.delivery_days,
            questions: formQuestions,
            submitted_bid_amount: form.bid_amount,
            submitted_delivery_days: form.delivery_days,
        });
        lastProjectId = result.project.id;
        lastBidId = result.bid.id;
        const freelancerId = scraped.freelancer_project_id || extractProjectId();
        if (freelancerId)
            markProjectSubmittedLocally(freelancerId);
        lastAutoGeneratedKey = projectPageKey();
        setBidEstimatesVisible(false);
        toast("Bid saved to dashboard");
    }
    catch (e) {
        toast(e instanceof Error ? e.message : "Failed to save bid", "error");
    }
    finally {
        window.setTimeout(() => {
            placeBidSaving = false;
        }, 2000);
    }
}
function handlePlaceBidEvent(event) {
    const target = event.target;
    if (!(target instanceof HTMLElement))
        return;
    if (target.closest(".ba-panel, .ba-fab"))
        return;
    const btn = target.closest("button, input[type='submit'], a, fl-button, [role='button'], [type='submit']");
    if (btn && isBidSubmitButton(btn)) {
        lastAutoGeneratedKey = projectPageKey();
        void onPlaceBidClicked();
        return;
    }
    if (event.type === "submit" && target instanceof HTMLFormElement && isBidForm(target)) {
        void onPlaceBidClicked();
    }
}
function attachPlaceBidWatcher() {
    if (placeBidWatcherAttached)
        return;
    placeBidWatcherAttached = true;
    document.addEventListener("click", handlePlaceBidEvent, true);
    document.addEventListener("mousedown", handlePlaceBidEvent, true);
    document.addEventListener("submit", handlePlaceBidEvent, true);
}
